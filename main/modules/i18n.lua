M.lang = "ru"

function M.detect()
	local l = sys.get_sys_info().language or "en"
	l = string.lower(string.sub(l, 1, 2))
	return STRINGS[l] and l or "en"
end

function M.set(lang)
	M.lang = STRINGS[lang] and lang or "ru"
end

function M.has(key)
	return STRINGS[M.lang][key] ~= nil or STRINGS.en[key] ~= nil
end

function M.t(key, vars)
	local s = (STRINGS[M.lang] and STRINGS[M.lang][key]) or STRINGS.en[key] or key
	if vars then
		for k, v in pairs(vars) do
			s = string.gsub(s, "{" .. k .. "}", (string.gsub(tostring(v), "%%", "%%%%")))
		end
	end
	return s
end

function M.fmt_time(sec)
	sec = math.max(0, math.floor(sec))
	if sec >= 3600 then
		local h = math.floor(sec / 3600)
		local m = math.floor((sec % 3600) / 60)
		return M.t("TIME_H", { h = h, m = string.format("%02d", m) })
	elseif sec >= 60 then
		local m = math.floor(sec / 60)
		local s = sec % 60
		return string.format("%d:%02d", m, s)
	end
	return string.format("0:%02d", sec)
end

-- Debug helper for tests: every key of every language.
function M.keys(lang)
	local out = {}
	for k in pairs(STRINGS[lang or "en"]) do out[#out + 1] = k end
	return out
end

return M
